import fs from 'node:fs/promises';
import path from 'node:path';

const manifestPath = path.resolve('public/images/manifest.json');
const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'));

const entries = manifest.map((m) => {
  const largest = m.variants[m.variants.length - 1];
  const srcSet = m.variants.map((v) => `${v.file} ${v.w}w`).join(', ');
  return `  '${m.name}': {
    src: '${largest.file}',
    srcSet: '${srcSet}',
    width: ${largest.w},
    height: ${largest.h},
    lqip: '${m.lqip}',
    credit: { source: '${m.sourceUrl.includes('pexels') ? 'Pexels' : 'Unsplash'}', url: '${m.sourceUrl}', query: '${m.sourceQuery}' },
  },`;
});

const content = `// Auto-generated by scripts/build-image-manifest.mjs — do not edit by hand.
export type ImageAsset = {
  src: string;
  srcSet: string;
  width: number;
  height: number;
  /** Tiny blur placeholder (data URI) */
  lqip: string;
  credit: { source: string; url: string; query: string };
};

export const images = {
${entries.join('\n')}
} satisfies Record<string, ImageAsset>;

export type ImageName = keyof typeof images;
`;
await fs.mkdir('src/content', { recursive: true });
await fs.writeFile('src/content/images.ts', content);
console.log('written', entries.length);
